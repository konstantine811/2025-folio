import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const exports = {};
vm.runInNewContext(ts.transpileModule(readFileSync(new URL('../src/components/page-partials/pages/experimental/three-scenes/games/rts-farmer/navigation/pathfinding.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports });
const { findPath, segmentClear, avoid, sidewalk } = exports;
const building = [{ x: 0, z: 15, hx: 3, hz: 4 }];
const path = findPath({ x: -10, z: 15 }, { x: 10, z: 15 }, building);
assert.ok(path.length > 0);
for (let i = 1; i < path.length; i++) assert.ok(segmentClear(path[i - 1], path[i], building), 'No corner cutting through inflated obstacles');
assert.equal(findPath({ x: -10, z: 15 }, { x: 0, z: 15 }, building).length, 0);
assert.equal(findPath({ x: 0, z: 0 }, { x: 60, z: 0 }, []).length, 0);
const pavement = findPath({ x: -20, z: 13 }, { x: 20, z: 13 }, []);
assert.ok(pavement.filter(sidewalk).length > pavement.length * 0.7, 'Prefer pavement even with a shorter grass route');
const right = avoid({ x: 1, z: 0 }, { x: -1, z: 0 }, [{ x: 1, z: 0, radius: 0.5 }], 1);
const left = avoid({ x: -1, z: 0 }, { x: 1, z: 0 }, [{ x: -1, z: 0, radius: 0.5 }], -1);
assert.ok(right.z < 0 && left.z > 0, 'Head-on agents choose opposite passing lanes');
const yieldToPlayer = avoid({ x: 0, z: 0 }, { x: 0, z: 0 }, [{ x: 0.5, z: 0, radius: 0.7 }], 1);
assert.ok(yieldToPlayer.x < 0, 'Idle agents also yield');
const overlap = avoid({ x: 0, z: 0 }, { x: 0, z: 0 }, [{ x: 0, z: 0, radius: 0.5 }], 1);
assert.ok(Number.isFinite(overlap.x) && Math.hypot(overlap.x, overlap.z) <= 1);
console.log('PASS: obstacle clearance, corner cutting, unreachable goals, sidewalk preference, head-on passing, idle yielding, finite overlap recovery');
